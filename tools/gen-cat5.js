const XVAR = ['', '（经济装）', '（家庭装）', '（便携装）', '（进口款）', '（儿童款）', '（促销装）', '（礼盒装）', '（散称）', '（大包装）', '（整箱）', '（补充装）'];

/** 把 total 均分到 n 个槽（余数给前几个），保证 sum === total 且每个 >=1 */
function spread(total, n) {
  if (n <= 0) return [];
  const base = Math.floor(total / n), rem = total - base * n;
  const out = [];
  for (let i = 0; i < n; i++) out.push(base + (i < rem ? 1 : 0));
  return out;
}

function build() {
  const flat = [];   // {code,name,level,parent,ord}
  let daCount = 0, zhongCount = 0, xiaoCount = 0, chuCount = 0;
  const seen = new Set();

  const push = (code, name, level, parent, ord) => {
    if (seen.has(code)) throw new Error('编码重复: ' + code);
    seen.add(code);
    flat.push({ code, name, level, parent: parent || '', ord });
  };

  for (const dept of DEPTS) {
    push(dept.code, dept.name, 1, '', 0);
    chuCount += dept.chu.length;
    for (const chu of dept.chu) {
      push(chu.code, chu.name, 2, dept.code, 0);
      daCount += chu.da.length;

      const daCodes = [];
      chu.da.forEach((da, i) => {
        const aCode = chu.code + String(i + 1).padStart(2, '0');
        daCodes.push(aCode);
        push(aCode, da.n, 3, chu.code, i);
      });

      const zCounts = spread(chu.nz, chu.da.length);
      // 该处级全部中类（按大类顺序展开）
      const zhongSlots = [];   // {aCode, mCode, name, xaList}
      chu.da.forEach((da, di) => {
        const aCode = daCodes[di];
        let zlist = z(da.z);
        const need = zCounts[di];
        for (let p = 0; zlist.length < need; p++) zlist.push(ZPAD[p % ZPAD.length] + (p >= ZPAD.length ? (Math.floor(p / ZPAD.length) + 1) : ''));
        for (let mi = 0; mi < need; mi++) {
          const mCode = aCode + String(mi + 1).padStart(2, '0');
          zhongSlots.push({ aCode, mCode, name: zlist[mi] || (da.n + '常规'), xaList: z(da.x), ord: mi });
        }
      });
      zhongCount += zhongSlots.length;

      const xCounts = spread(chu.nx, zhongSlots.length);
      zhongSlots.forEach((mm, idx) => {
        push(mm.mCode, mm.name, 4, mm.aCode, mm.ord);
        const xn = xCounts[idx];
        const nouns = mm.xaList.length ? mm.xaList : [mm.name];
        const seenIn = new Set();
        for (let x = 0; x < xn; x++) {
          const noun = nouns[(x + idx * 3) % nouns.length];
          const v = XVAR[Math.floor(x / nouns.length) % XVAR.length];
          let nm = noun + v;
          let guard = 0;
          while (seenIn.has(nm) && guard < 500) { nm = noun + v + '·' + (++guard); }
          seenIn.add(nm);
          const xCode = mm.mCode + String(x + 1).padStart(2, '0');
          push(xCode, nm, 5, mm.mCode, x);
        }
        xiaoCount += xn;
      });
    }
  }

  return { flat, stat: { dept: DEPTS.length, chu: chuCount, da: daCount, zhong: zhongCount, xiao: xiaoCount } };
}

